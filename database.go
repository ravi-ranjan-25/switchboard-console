package main

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
)

// Per-app Postgres on the shared CNPG cluster `db` (namespace configs). For app X this creates:
//   apps/db/cluster.yaml          managed role X (password from Secret db-X)
//   apps/db/databases.yaml        Database X (owner X, reclaim retain)
//   apps/db/externalsecret.yaml   ExternalSecret db-X (basic-auth Secret for the role, from vault key keep--X-db-password)
//   apps/db/dump-cronjob.yaml     X added to the nightly dump list
//   bootstrap/vault/mapping.yaml  keep--X-db-password (generated)
//   bootstrap/secrets.catalog.yaml  X_db_password in the generated list
//   apps/X/externalsecret.yaml    DATABASE_URL built from the SAME generated password (one source of truth)
//   clusters/keep/apps/X.yaml     db-client component + dependsOn db
// Every edit is a textual splice, idempotent (ErrAlready when the piece is there) and verified by re-parsing.
// Switchboard cannot create the password: it is generated by `make secrets` and pushed with `make vault-push`.

var ErrAlready = errors.New("already present")

func dbName(app string) string      { return strings.ReplaceAll(app, "-", "_") }
func dbVaultKey(app string) string  { return "keep--" + app + "-db-password" }
func dbSecretKey(app string) string { return dbName(app) + "_db_password" }

func lineIndex(ed *lineEditor, pred func(string) bool) int {
	for i, l := range ed.lines {
		if pred(l) {
			return i
		}
	}
	return -1
}

// blockEnd returns the index after the last non-blank line of the block that starts at start (exclusive) and whose lines
// are indented deeper than indent.
func blockEnd(ed *lineEditor, start, indent int) int {
	end := start + 1
	for i := start + 1; i < len(ed.lines); i++ {
		t := strings.TrimSpace(ed.lines[i])
		if t == "" {
			continue
		}
		if indentOf(ed.lines[i]) <= indent && !strings.HasPrefix(t, "#") {
			break
		}
		end = i + 1
	}
	return end
}

func insertLines(ed *lineEditor, at int, ins []string) {
	ed.lines = append(ed.lines[:at], append(append([]string{}, ins...), ed.lines[at:]...)...)
}

// AddDBRole appends a managed role to apps/db/cluster.yaml.
func AddDBRole(content []byte, app string) ([]byte, error) {
	docs, err := decodeDocs(content)
	if err != nil || len(docs) != 1 {
		return nil, errors.New("cluster.yaml: expected one document")
	}
	for _, r := range list(dig(docs[0], "spec", "managed", "roles")) {
		if str(dig(r, "name")) == dbName(app) {
			return nil, ErrAlready
		}
	}
	ed := newLineEditor(content)
	i := lineIndex(ed, func(l string) bool { return strings.TrimRight(l, " ") == "    roles:" })
	if i < 0 {
		return nil, errors.New("cluster.yaml: spec.managed.roles block not found (unsupported layout)")
	}
	end := blockEnd(ed, i, 4)
	insertLines(ed, end, []string{"      - name: " + dbName(app), "        ensure: present", "        login: true", "        passwordSecret:", "          name: db-" + app})
	out := ed.bytes()
	chk, _ := decodeDocs(out)
	found := false
	if len(chk) == 1 {
		for _, r := range list(dig(chk[0], "spec", "managed", "roles")) {
			found = found || (str(dig(r, "name")) == dbName(app) && str(dig(r, "passwordSecret", "name")) == "db-"+app)
		}
	}
	if !found {
		return nil, errors.New("role edit failed verification")
	}
	return out, nil
}

func appendDoc(content []byte, doc string, kindName, name string) ([]byte, error) {
	docs, err := decodeDocs(content)
	if err != nil {
		return nil, err
	}
	for _, d := range docs {
		if kind(d) == kindName && str(dig(d, "metadata", "name")) == name {
			return nil, ErrAlready
		}
	}
	s := strings.TrimRight(string(content), "\n")
	out := []byte(s + "\n---\n" + strings.TrimLeft(doc, "\n"))
	chk, err := decodeDocs(out)
	if err != nil || len(chk) != len(docs)+1 {
		return nil, errors.New("appended document failed verification")
	}
	return out, nil
}

func AddDBDatabase(content []byte, app string) ([]byte, error) {
	return appendDoc(content, fmt.Sprintf(`apiVersion: postgresql.cnpg.io/v1
kind: Database
metadata:
  name: %[1]s
  namespace: configs
  labels:
    citadel.dev/app: db
spec:
  cluster: {name: db}
  name: %[2]s
  owner: %[2]s
  databaseReclaimPolicy: retain
`, app, dbName(app)), "Database", app)
}

func AddDBExternalSecret(content []byte, app string) ([]byte, error) {
	return appendDoc(content, fmt.Sprintf(`apiVersion: external-secrets.io/v1
kind: ExternalSecret
metadata:
  name: db-%[1]s
  namespace: configs
spec:
  refreshInterval: 1h
  secretStoreRef: {kind: ClusterSecretStore, name: oci-vault}
  target:
    name: db-%[1]s
    creationPolicy: Owner
    template:
      type: kubernetes.io/basic-auth
      metadata:
        labels:
          cnpg.io/reload: "true"
      data:
        username: %[2]s
        password: "{{ .password }}"
  data:
    - secretKey: password
      remoteRef:
        key: %[3]s
`, app, dbName(app), dbVaultKey(app)), "ExternalSecret", "db-"+app)
}

var dumpForRe = regexp.MustCompile(`(for d in )([a-z0-9_ -]+)(; do)`)

// AddDumpDB adds the database to the nightly pg_dump loop.
func AddDumpDB(content []byte, app string) ([]byte, error) {
	m := dumpForRe.FindSubmatchIndex(content)
	if m == nil {
		return nil, errors.New("dump-cronjob.yaml: `for d in ...; do` loop not found (unsupported layout)")
	}
	cur := strings.Fields(string(content[m[4]:m[5]]))
	if contains(cur, dbName(app)) {
		return nil, ErrAlready
	}
	out := string(content[:m[5]]) + " " + dbName(app) + string(content[m[5]:])
	if !dumpForRe.MatchString(out) || !strings.Contains(out, " "+dbName(app)+"; do") {
		return nil, errors.New("dump edit failed verification")
	}
	return []byte(out), nil
}

// AddMappingLine adds `keep--X-db-password: {key: X_db_password, source: generated}` after the last *-db-password line, aligned like its neighbours.
func AddMappingLine(content []byte, app string) ([]byte, error) {
	name := dbVaultKey(app)
	ed := newLineEditor(content)
	if lineIndex(ed, func(l string) bool { return strings.HasPrefix(strings.TrimSpace(l), name+":") }) >= 0 {
		return nil, ErrAlready
	}
	last := -1
	for i, l := range ed.lines {
		if strings.Contains(l, "-db-password:") && strings.Contains(l, "source: generated") {
			last = i
		}
	}
	if last < 0 {
		return nil, errors.New("mapping.yaml: no existing *-db-password line to align with")
	}
	ref := ed.lines[last]
	kc, sc := strings.Index(ref, "{key:"), strings.Index(ref, "source:")
	if kc < 0 || sc < kc {
		return nil, errors.New("mapping.yaml: unexpected line layout")
	}
	pad := func(s string, w int) string {
		if len(s) >= w {
			return s + " "
		}
		return s + strings.Repeat(" ", w-len(s))
	}
	line := pad("  "+name+":", kc) + pad("{key: "+dbSecretKey(app)+",", sc-kc) + "source: generated}"
	insertLines(ed, last+1, []string{line})
	out := ed.bytes()
	chk := newLineEditor(out)
	if lineIndex(chk, func(l string) bool {
		return strings.Contains(l, name+":") && strings.Contains(l, "key: "+dbSecretKey(app)+",")
	}) < 0 {
		return nil, errors.New("mapping edit failed verification")
	}
	return out, nil
}

// AddCatalogGenerated adds `- { key: X_db_password, bytes: 32, encoding: base64 }` to the generated list.
func AddCatalogGenerated(content []byte, app string) ([]byte, error) {
	key := dbSecretKey(app)
	ed := newLineEditor(content)
	if lineIndex(ed, func(l string) bool { return strings.Contains(l, "{ key: "+key+",") }) >= 0 {
		return nil, ErrAlready
	}
	last := -1
	for i, l := range ed.lines {
		if strings.Contains(l, "_db_password,") && strings.Contains(l, "bytes: 32") {
			last = i
		}
	}
	if last < 0 {
		return nil, errors.New("secrets.catalog.yaml: no existing *_db_password entry in the generated list to align with")
	}
	ref := ed.lines[last]
	bc := strings.Index(ref, "bytes:")
	kc := strings.Index(ref, "{ key:")
	if bc < 0 || kc < 0 {
		return nil, errors.New("secrets.catalog.yaml: unexpected entry layout")
	}
	w := bc - kc
	head := "{ key: " + key + ","
	if len(head) < w {
		head += strings.Repeat(" ", w-len(head))
	} else {
		head += " "
	}
	insertLines(ed, last+1, []string{ref[:kc] + head + "bytes: 32, encoding: base64 }"})
	out := ed.bytes()
	if lineIndex(newLineEditor(out), func(l string) bool { return strings.Contains(l, "{ key: "+key+",") }) < 0 {
		return nil, errors.New("catalog edit failed verification")
	}
	return out, nil
}

// SetDatabaseURL rewires the app's ExternalSecret so DATABASE_URL is built from the generated db password.
func SetDatabaseURL(content []byte, app string) ([]byte, error) {
	docs, err := decodeDocs(content)
	if err != nil || len(docs) != 1 || kind(docs[0]) != "ExternalSecret" {
		return nil, errors.New("not a single-document ExternalSecret")
	}
	d := docs[0]
	url := fmt.Sprintf(`postgresql://%s:{{ .db_password | urlquery }}@db-rw.configs.svc.cluster.local:5432/%s`, dbName(app), dbName(app))
	hasData := false
	for _, e := range list(dig(d, "spec", "data")) {
		hasData = hasData || (str(dig(e, "secretKey")) == "db_password" && str(dig(e, "remoteRef", "key")) == dbVaultKey(app))
	}
	if str(dig(d, "spec", "target", "template", "data", "DATABASE_URL")) != "" && hasData {
		return nil, ErrAlready
	}
	if dig(d, "spec", "target", "template") != nil {
		return nil, errors.New("the ExternalSecret already has a target.template; add DATABASE_URL by hand")
	}
	if len(list(dig(d, "spec", "dataFrom"))) > 0 {
		return nil, errors.New("the ExternalSecret uses dataFrom; unsupported")
	}
	ed := newLineEditor(content)
	t := lineIndex(ed, func(l string) bool { return strings.TrimRight(l, " ") == "  target:" })
	if t < 0 {
		return nil, errors.New("spec.target block not found (unsupported layout)")
	}
	tmpl := []string{"    template:", "      engineVersion: v2", "      mergePolicy: Merge", "      data:",
		"        # One source of truth: the same generated password the db cluster gives the " + dbName(app) + " role.",
		`        DATABASE_URL: "` + url + `"`}
	// data list first (later in the file), so earlier line numbers stay valid
	di := lineIndex(ed, func(l string) bool { return strings.TrimRight(l, " ") == "  data:" })
	if di < 0 {
		return nil, errors.New("spec.data block not found (unsupported layout)")
	}
	entry := []string{"    - secretKey: db_password", "      remoteRef:", "        key: " + dbVaultKey(app)}
	old := -1
	for i := di + 1; i < blockEnd(ed, di, 2); i++ {
		if strings.TrimSpace(ed.lines[i]) == "- secretKey: DATABASE_URL" {
			old = i
		}
	}
	if old >= 0 { // replace the hand-entered DATABASE_URL entry (3 lines: secretKey, remoteRef, key)
		end := old + 1
		for end < len(ed.lines) && indentOf(ed.lines[end]) > 4 && strings.TrimSpace(ed.lines[end]) != "" {
			end++
		}
		ed.lines = append(ed.lines[:old], append(append([]string{}, entry...), ed.lines[end:]...)...)
	} else if !hasData {
		insertLines(ed, di+1, entry)
	}
	insertLines(ed, blockEnd(ed, t, 2), tmpl)
	out := ed.bytes()
	chk, err := decodeDocs(out)
	if err != nil || len(chk) != 1 || str(dig(chk[0], "spec", "target", "template", "data", "DATABASE_URL")) != url {
		return nil, errors.New("DATABASE_URL edit failed verification")
	}
	ok := false
	for _, e := range list(dig(chk[0], "spec", "data")) {
		ok = ok || (str(dig(e, "secretKey")) == "db_password" && str(dig(e, "remoteRef", "key")) == dbVaultKey(app))
	}
	if !ok {
		return nil, errors.New("db_password entry missing after edit")
	}
	return out, nil
}

// EnsureDBClient makes sure the app's Flux Kustomization has the db-client component and depends on db.
func EnsureDBClient(content []byte) ([]byte, error) {
	docs, err := decodeDocs(content)
	if err != nil || len(docs) == 0 {
		return nil, errors.New("not a Flux Kustomization")
	}
	hasComp := containsAny(strList(dig(docs[0], "spec", "components")), "components/db-client")
	hasDep := false
	for _, x := range list(dig(docs[0], "spec", "dependsOn")) {
		hasDep = hasDep || str(dig(x, "name")) == "db"
	}
	if hasComp && hasDep {
		return nil, ErrAlready
	}
	ed := newLineEditor(content)
	if !hasComp {
		i := lineIndex(ed, func(l string) bool { return strings.TrimRight(l, " ") == "  components:" })
		if i < 0 {
			return nil, errors.New("spec.components block not found")
		}
		// after the last UNCOMMENTED list item of the block
		end := i + 1
		for j := i + 1; j < len(ed.lines); j++ {
			t := strings.TrimSpace(ed.lines[j])
			if t == "" || (indentOf(ed.lines[j]) <= 2 && !strings.HasPrefix(t, "#")) {
				break
			}
			if strings.HasPrefix(t, "- ") {
				end = j + 1
			}
		}
		insertLines(ed, end, []string{"    - ../../components/db-client"})
	}
	if !hasDep {
		i := lineIndex(ed, func(l string) bool { return strings.TrimRight(l, " ") == "  dependsOn:" })
		if i < 0 {
			return nil, errors.New("spec.dependsOn block not found")
		}
		insertLines(ed, blockEnd(ed, i, 2), []string{"    - name: db"})
	}
	out := ed.bytes()
	chk, err := decodeDocs(out)
	if err != nil || len(chk) == 0 || !containsAny(strList(dig(chk[0], "spec", "components")), "components/db-client") {
		return nil, errors.New("db-client edit failed verification")
	}
	dep := false
	for _, x := range list(dig(chk[0], "spec", "dependsOn")) {
		dep = dep || str(dig(x, "name")) == "db"
	}
	if !dep {
		return nil, errors.New("dependsOn edit failed verification")
	}
	return out, nil
}
